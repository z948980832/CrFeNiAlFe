#!/usr/bin/env python3
"""Plot predicted versus actual UTS and EL for the held-out SPXY test set."""

from __future__ import annotations

import argparse
import csv
import math
from pathlib import Path
from typing import Dict, List, Tuple

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt


REQUIRED_COLUMNS = (
    "UTS_actual",
    "UTS_predicted",
    "EL_actual",
    "EL_predicted",
)


def parse_args() -> argparse.Namespace:
    script_dir = Path(__file__).resolve().parent
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--data",
        type=Path,
        default=script_dir / "test_predictions.csv",
        help="SPXY test prediction CSV generated by test_fcnn.py.",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=script_dir / "test_predictions_scatter.png",
    )
    return parser.parse_args()


def read_predictions(path: Path) -> Dict[str, List[float]]:
    with path.open("r", encoding="utf-8-sig", newline="") as handle:
        reader = csv.DictReader(handle)
        if reader.fieldnames is None:
            raise ValueError(f"CSV has no header: {path}")
        missing = [name for name in REQUIRED_COLUMNS if name not in reader.fieldnames]
        if missing:
            raise ValueError(f"CSV is missing columns: {missing}")

        values = {name: [] for name in REQUIRED_COLUMNS}
        for line_number, row in enumerate(reader, start=2):
            for name in REQUIRED_COLUMNS:
                try:
                    value = float(row[name])
                except (TypeError, ValueError) as exc:
                    raise ValueError(
                        f"Line {line_number}, column {name} is not numeric."
                    ) from exc
                if not math.isfinite(value):
                    raise ValueError(
                        f"Line {line_number}, column {name} is not finite."
                    )
                values[name].append(value)

    if not values[REQUIRED_COLUMNS[0]]:
        raise ValueError("CSV contains no data rows.")
    return values


def regression_metrics(
    actual: List[float], predicted: List[float]
) -> Tuple[float, float, float]:
    mean_actual = sum(actual) / len(actual)
    residual_sum = sum(
        (prediction - truth) ** 2 for truth, prediction in zip(actual, predicted)
    )
    total_sum = sum((truth - mean_actual) ** 2 for truth in actual)
    r2 = 1.0 - residual_sum / total_sum if total_sum > 0.0 else math.nan
    rmse = math.sqrt(residual_sum / len(actual))
    mae = sum(
        abs(prediction - truth) for truth, prediction in zip(actual, predicted)
    ) / len(actual)
    return r2, rmse, mae


def draw_panel(
    axis,
    actual: List[float],
    predicted: List[float],
    target: str,
    color: str,
) -> Tuple[float, float, float]:
    lower = min(actual + predicted)
    upper = max(actual + predicted)
    span = upper - lower
    margin = 0.07 * span if span > 0.0 else 1.0
    limits = (lower - margin, upper + margin)

    axis.scatter(
        actual,
        predicted,
        s=58,
        color=color,
        edgecolor="white",
        linewidth=0.8,
        alpha=0.9,
        zorder=3,
    )
    axis.plot(
        limits,
        limits,
        color="#374151",
        linewidth=1.25,
        linestyle="--",
        zorder=2,
    )
    axis.set_xlim(limits)
    axis.set_ylim(limits)
    axis.set_aspect("equal", adjustable="box")
    axis.set_xlabel(f"Actual {target}", fontsize=11)
    axis.set_ylabel(f"Predicted {target}", fontsize=11)
    axis.set_title(f"{target}: predicted vs actual", loc="left", fontsize=12, weight="bold")
    axis.tick_params(labelsize=9)
    axis.grid(True, color="#E5E7EB", linewidth=0.7)
    axis.set_axisbelow(True)

    r2, rmse, mae = regression_metrics(actual, predicted)
    axis.text(
        0.04,
        0.96,
        f"n = {len(actual)}\n$R^2$ = {r2:.4f}\nRMSE = {rmse:.3f}\nMAE = {mae:.3f}",
        transform=axis.transAxes,
        ha="left",
        va="top",
        fontsize=9.5,
        bbox={
            "boxstyle": "round,pad=0.35",
            "facecolor": "white",
            "edgecolor": "#D1D5DB",
            "alpha": 0.92,
        },
    )
    return r2, rmse, mae


def main() -> None:
    args = parse_args()
    values = read_predictions(args.data.resolve())

    fig, axes = plt.subplots(1, 2, figsize=(11.8, 5.4))
    uts_metrics = draw_panel(
        axes[0],
        values["UTS_actual"],
        values["UTS_predicted"],
        "UTS",
        "#2563EB",
    )
    el_metrics = draw_panel(
        axes[1],
        values["EL_actual"],
        values["EL_predicted"],
        "EL",
        "#EA580C",
    )
    fig.suptitle(
        "SPXY held-out test set: predictions and actual values",
        fontsize=14,
        weight="bold",
    )
    fig.text(
        0.5,
        0.015,
        "Dashed line: ideal prediction (y = x)",
        ha="center",
        fontsize=9,
        color="#4B5563",
    )
    fig.tight_layout(rect=(0, 0.045, 1, 0.94))

    output_path = args.output.resolve()
    output_path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(output_path, dpi=220, bbox_inches="tight", facecolor="white")
    plt.close(fig)

    print(f"Rows plotted: {len(values['UTS_actual'])}")
    print(
        f"UTS R2={uts_metrics[0]:.6f}, RMSE={uts_metrics[1]:.6f}, "
        f"MAE={uts_metrics[2]:.6f}"
    )
    print(
        f"EL  R2={el_metrics[0]:.6f}, RMSE={el_metrics[1]:.6f}, "
        f"MAE={el_metrics[2]:.6f}"
    )
    print(f"Output: {output_path}")


if __name__ == "__main__":
    main()
